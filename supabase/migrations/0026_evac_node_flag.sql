-- =============================================================
-- 0026_evac_node_flag.sql — แยก "จุดส่งกลับ" ออกจาก "หน่วยที่มีอยู่ในระบบ"
--
-- ทำไมต้องมีไฟล์นี้ (เจอตอนเปิดหน้า /monitor ด้วยเบราว์เซอร์จริง 9 ก.ย. 2569)
--   ผังสายการส่งกลับวาดจากตาราง unit ทั้งตาราง ผลคือ 'ศูนย์สั่งการส่งกลับ'
--   ไปยืนอยู่ในชั้น 2 พร้อมป้าย "เตียงว่าง 0" ทั้งที่มันไม่ใช่ปลายทางของใคร
--   และ 0 ตรงนั้นอ่านได้ว่า "เต็มแล้ว" ซึ่งเป็นคนละเรื่องกับ "ไม่ใช่ที่รับผู้ป่วย"
--
--   เจ้าของโครงการนิยามงานของ monitor ไว้ว่ารวมถึง
--   "จำนวนจุดที่**ตั้งเป็น**จุดส่งกลับ" — คำว่าตั้งเป็นแปลว่ามีการกำหนด
--   ไม่ใช่ทุกหน่วยในระบบเป็นจุดส่งกลับโดยอัตโนมัติ schema เดิมแยกสองอย่างนี้ไม่ได้เลย
--
-- ★ default true โดยเจตนา
--   หน่วยที่มีอยู่แล้วทุกแถวยังแสดงบนผังเหมือนเดิมหลังรัน migration
--   ถ้า default เป็น false ผังจะว่างเปล่าทันทีที่ deploy ซึ่งดูเหมือนระบบพัง
--   การถอดหน่วยออกจากผังต้องเป็นการกระทำที่ตั้งใจ ไม่ใช่ผลข้างเคียงของการอัปเกรด
--
-- ★ ไม่ใช้ role_level ตัดสินแทน
--   ศูนย์สั่งการเป็น role_2 เท่ากับที่พยาบาลกองพล การกรองด้วยชั้นจึงตัดผิดตัว
--
-- ⚠ backward compatible — คอลัมน์เดียว มี default ไม่มี constraint ที่กระทบแถวเดิม
-- =============================================================

alter table public.unit
  add column is_evac_node boolean not null default true;

comment on column public.unit.is_evac_node is
  'หน่วยนี้ถูกตั้งเป็นจุดส่งกลับที่รับผู้ป่วยได้หรือไม่ · false สำหรับหน่วยอำนวยการที่ไม่ได้รับผู้ป่วย เช่นศูนย์สั่งการ · ใช้กรองผังสายส่งกลับบนแดชบอร์ด';

-- ศูนย์สั่งการเป็นที่ทำงานของคนที่จัดสรรจุดส่งกลับ ไม่ใช่จุดส่งกลับเอง
update public.unit set is_evac_node = false where code = 'DEMO-CTRL';

