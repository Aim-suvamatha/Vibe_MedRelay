-- =============================================================
-- 0024_case_diagnosis.sql — ช่องวินิจฉัยของแพทย์ปลายทาง
--
-- ทำไมเพิ่งมามีตอนนี้
--   0020 ตัด diagnosis ออกจากฟอร์มผู้ส่งโดยเจตนา ด้วยเหตุผลว่า
--   "ผู้ส่งไม่วินิจฉัย เป็นหน้าที่แพทย์ปลายทาง (icd10 มีอยู่แล้วใน 0013)"
--   รอบนี้คือการเติมให้ครบตามเหตุผลนั้น ไม่ใช่การรื้อการตัดสินใจเดิม
--
-- ทำไม icd10 ช่องเดียวไม่พอ (เจ้าของโครงการเจอตอนทดสอบด้วยมือ 9 ก.ย. 2569)
--   คนที่กรอกหน้างานจำรหัส ICD-10 ไม่ได้ ถ้ามีแต่ช่องรหัส เขาจะเว้นว่างทิ้ง
--   แล้วข้อมูลวินิจฉัยหายไปทั้งก้อน ทั้งที่เขา "รู้" ว่าผู้ป่วยเป็นอะไร
--   จึงต้องมีช่องข้อความคู่กัน — รหัสใส่ก็ได้ไม่ใส่ก็ได้ แต่คำวินิจฉัยต้องลงได้เสมอ
--
-- ★ backward compatible โดยเจตนา
--   เป็น add column เปล่าๆ ไม่มี constraint ไม่มี default ไม่มี not null
--   โค้ดเก่าที่ยังรันอยู่บน production ระหว่างรอ deploy ทำงานได้ปกติทุกอย่าง
--   จึงไม่มีช่องอันตรายแบบที่ 0022 เคยเปิดไว้ (ดู HANDOFF หัวข้อ deploy)
--
-- ★ ไม่แตะ enum case_outcome
--   ป้าย "คงพยาบาล" ถูกเปลี่ยนเป็น "รับป่วย ดูอาการที่จุดนี้" เฉพาะบนหน้าจอ
--   ค่าในฐานข้อมูลยังเป็น 'hospitalized' ตามศัพท์ของ ทบ.466-900 เหมือนเดิม
--   เพราะรายงานที่ส่งหน่วยเหนือต้องใช้คำของแบบฟอร์ม ไม่ใช่คำที่ใช้คุยกันหน้างาน
-- =============================================================

alter table public."case"
  add column if not exists diagnosis text;

comment on column public."case".diagnosis is
  'คำวินิจฉัยของแพทย์ปลายทาง เป็นข้อความอิสระ — คู่กับ icd10 ซึ่งเป็นรหัสและไม่บังคับ';
