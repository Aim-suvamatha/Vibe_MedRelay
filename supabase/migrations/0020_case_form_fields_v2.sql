-- ช่องที่เคยอยู่ในร่างแรกแล้วถูกตัดออกตามคำสั่งเจ้าของโครงการ (8 ก.ย. 2569)
--   diagnosis      — ผู้ส่งไม่วินิจฉัย เป็นหน้าที่แพทย์ปลายทาง (icd10 มีอยู่แล้วใน 0013)
--   diet           — ช่องอาหารตัดออกจากฟอร์มผู้ส่ง
