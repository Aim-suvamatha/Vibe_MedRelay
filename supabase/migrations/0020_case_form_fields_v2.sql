alter table public."case"
  -- ฐานปฏิบัติการ (แถบข้อมูลด้านล่างของบัตรบันทึกการเจ็บป่วยในสนาม)
  -- ต่างจาก injury_place ที่เป็น "จุดเกิดเหตุ" — ทหารอาจบาดเจ็บนอกฐานที่ตัวเองประจำอยู่
  add column operating_base   text,

  -- ช่อง "บันทึกอื่นๆ" ท้าย ทบ.466-901 ด้านหน้า
  add column other_note       text,

  -- ประเภทผู้ป่วย: บาดเจ็บยุทธการ · ธุรการ · อื่นๆ
  add column patient_category public.patient_category,

  -- สามแถวติ๊กมุมบนขวาของ ทบ.466-901 ด้านหลัง
  -- เป็นสภาพ ณ ขณะส่งมอบ ไม่ใช่รายการหัตถการ จึงอยู่ที่นี่ไม่ใช่ในตาราง treatment
  -- ค่า 'normal' คือการบันทึกว่าตรวจแล้วไม่พบอะไร ซึ่งตาราง treatment เก็บไม่ได้
  add column airway_status    public.airway_status,
  add column chest_status     public.chest_status,
  add column wound_status     public.wound_status;

comment on column public."case".operating_base is
  'ฐานปฏิบัติการที่ผู้ป่วยสังกัด — ต่างจาก injury_place ซึ่งเป็นจุดที่เกิดเหตุจริง';
comment on column public."case".patient_category is
  'บาดเจ็บยุทธการ · ธุรการ · อื่นๆ — หยาบกว่า report_category โดยเจตนา เพราะหน้างานต้องเลือกได้ในหนึ่งวินาที';

-- =============================================================
-- เวลาที่รัดสายห้ามเลือด — ข้อยกเว้นเดียวของกฎ "ไม่มีช่องกรอกเวลา"
--
-- กฎเดิมจาก Prompt 04 คือเวลาทุกตัวเกิดจากการกดปุ่ม ห้าม client กำหนดเอง
-- เพื่อให้ตัวเลขเวลาตอบสนองบนแดชบอร์ดเชื่อถือได้
--
-- สายรัดห้ามเลือดต่างออกไปจริง เพราะมันถูกรัดก่อนที่เสนารักษ์จะได้หยิบเครื่องขึ้นมากรอก
-- ถ้าบันทึกเวลาที่กดปุ่มแทนเวลาที่รัดจริง **นาฬิกาขาดเลือดจะสั้นกว่าความจริง**
-- ซึ่งเป็นทิศทางที่อันตราย เพราะรัดเกิน 2 ชั่วโมงเสี่ยงต่อการสูญเสียอวัยวะ
--
-- ข้อยกเว้นนี้ไม่ทำให้กฎเดิมพัง เพราะ treatment.given_at **ไม่ได้ถูกใช้ในสูตรใด**
-- ของ v_leg_metrics หรือ v_case_metrics — ตัวเลขเวลาตอบสนองมาจาก timestamp
-- ของ transfer_leg ล้วนๆ ช่องนี้จึงปั่นตัวเลขบนแดชบอร์ดไม่ได้
--
-- ⚠ now() ใน CHECK เป็น non-immutable — Postgres ยอมและตรวจตอน insert/update ตามต้องการ
--   แต่ pg_dump แล้ว restore จะไม่ตรวจซ้ำ ด่านที่เชื่อถือได้จริงคือ create_evac_request
--   ซึ่งเป็นทางเข้าเดียวของข้อมูลชุดนี้ และตรวจไว้อีกชั้นแล้ว
-- =============================================================
alter table public.treatment
  add constraint treatment_given_not_future check (given_at <= now());

comment on column public.treatment.given_at is
  'เวลาที่ให้การรักษาจริง — ค่าปริยายคือเวลาที่กดปุ่ม แต่สายรัดห้ามเลือดแก้เป็นเวลาที่รัดจริงได้ (ดูหัวข้อใน 0020) · แก้ทีหลังไม่ได้เพราะ column grant ไม่ให้ update';
