-- =============================================================
-- 0012_form_enums.sql — enum ที่ถอดมาจากแบบฟอร์มกระดาษของจริง
--
-- ที่มาของทุก enum ในไฟล์นี้คือเอกสารต้นฉบับใน supabase/Report/
--   ทบ.466-900  รายงานการรักษาพยาบาลและการส่งกลับในสนาม
--   ทบ.466-901  บัตรบันทึกผู้ป่วยเจ็บในสนาม (แบบบันทึกการเจ็บป่วยในสนาม หน้า/หลัง)
--   ทบ.466-902  บัตรสำหรับคนไข้ส่งกลับ
--   ทบ.466-903  บัตรส่งสิ่งของคนไข้
--
-- หลักการเดิมของโครงการ: ไม่กำหนดหมวดขึ้นเอง ทุกค่ามาจากหลักนิยมหรือแบบฟอร์มที่หน่วยใช้อยู่แล้ว
-- ถ้าค่าใดไม่มีในกระดาษ แปลว่าเรากำลังเพิ่มภาระให้ผู้ใช้ ซึ่งขัดหลักการออกแบบของโครงการ
-- =============================================================

-- ชั้นยศสำหรับนับยอดใน ทบ.466-900 (คนละเรื่องกับ profile.rank_th ซึ่งเป็นยศเต็มของผู้ใช้ระบบ)
-- แบบฟอร์มนับยอดผู้ป่วยแยกเป็น 4 ช่องนี้เท่านั้น
create type public.rank_group as enum (
  'officer',    -- นายทหาร
  'nco',        -- นายสิบ
  'enlisted',   -- พลทหาร
  'volunteer'   -- อาสาสมัคร
);

-- หมวดสาเหตุตาม ทบ.466-900 — ใช้ลงยอดในรายงานประจำวันโดยไม่ต้องกรอกซ้ำ
create type public.report_category as enum (
  -- ๑. บาดเจ็บจากการรบ
  'combat_gunshot',       -- ๑.๑ ถูกยิง
  'combat_explosive',     -- ๑.๒ ถูกระเบิด
  'combat_mine',          -- ๑.๓ ถูกกับระเบิด
  'combat_other',         -- ๑.๔–๑.๕ อื่นๆ
  -- ๒. อุบัติเหตุจากการรบ
  'combat_accident',
  -- ๓. การบาดเจ็บสาเหตุอื่นๆ
  'noncombat_injury',
  -- การป่วยไข้
  'illness_respiratory',  -- ๑. โรคทางเดินหายใจ
  'illness_gi',           -- ๒. โรคทางเดินอาหาร
  'illness_malaria',      -- ๓. โรคมาลาเรีย
  'illness_std',          -- ๔. กามโรค
  'illness_other'         -- ๕–๘ อื่นๆ
);

-- ผลการรักษาตามช่องท้ายตารางของ ทบ.466-900
create type public.case_outcome as enum (
  'recovered',     -- หาย
  'hospitalized',  -- คงพยาบาล
  'died'           -- ตาย
);

-- ปลายทางการจำหน่าย — ทบ.466-900 แยกเป็นคนละกลุ่มคอลัมน์
-- returned_to_unit มาจากรายงานหน่วยเหนือที่ใช้คำว่า "รักษา/ส่งคืนหน่วยต้นสังกัด"
create type public.disposition_route as enum (
  'evac_chain',        -- ส่งไปรักษาตามสายการส่งกลับ
  'civilian_hospital', -- ส่งไปรักษา รพ.พลเรือน
  'returned_to_unit'   -- รักษาแล้วส่งคืนหน่วยต้นสังกัด
);

-- ระดับความรู้สึกตัวตามหมายเหตุท้าย ทบ.466-901 ด้านหลัง
--   ด = ตื่นดี · ร = เรียกตื่น · จ = เจ็บตื่น · ม = ไม่ตื่น
-- ตรงกับ AVPU สากล จึงเก็บเป็นชื่ออังกฤษแล้วให้ UI แปลเป็นคำไทยของแบบฟอร์ม
create type public.avpu_level as enum (
  'alert',        -- ด ตื่นดี
  'voice',        -- ร เรียกตื่น
  'pain',         -- จ เจ็บตื่น
  'unresponsive'  -- ม ไม่ตื่น
);

-- ยานพาหนะที่ "ขอ" ตามช่องใน ทบ.466-902 (เครื่องบิน/ฮ. · รถ · เรือ)
-- ต่างจาก vehicle_type ที่เป็นรถคันที่ศูนย์สั่งการ "จัดให้จริง"
create type public.transport_mode as enum (
  'ground',
  'rotary',      -- ฮ.
  'fixed_wing',  -- เครื่องบิน
  'watercraft'   -- เรือ
);

-- ประเภทคนไข้ตามช่องใน ทบ.466-902 — ศูนย์สั่งการใช้คำนวณว่าต้องใช้รถกี่คันและต้องมีคนคุมหรือไม่
create type public.patient_mobility as enum (
  'litter_dependent',  -- นอนช่วยตัวเองไม่ได้
  'litter_assisted',   -- นอนช่วยตัวเองได้
  'ambulatory',        -- เดินได้
  'psych_escort',      -- โรคจิตต้องนอนเฝ้า
  'psych_no_escort'    -- โรคจิตนอนไม่ต้องเฝ้า
);

-- สถานการณ์ ณ จุดรับ — จำเป็นต่อความปลอดภัยของชุดลำเลียง (ช่อง security ในคำขอ MEDEVAC 9 บรรทัด)
create type public.security_status as enum (
  'secure',           -- ปลอดภัย
  'possible_contact', -- อาจมีการปะทะ
  'active_contact'    -- มีการปะทะ
);

-- การปนเปื้อน NBC (nuclear/biological/chemical) — ช่องบังคับในคำขอ MEDEVAC
create type public.nbc_status as enum ('none', 'suspected', 'confirmed');

-- หัตถการและยาที่บันทึกได้ด้วยการกดปุ่มเดียว
-- ถอดจากช่องที่มีอยู่แล้วใน ทบ.466-901 ด้านหลัง (ทางเดินหายใจ · ปอด · แผล · น้ำเกลือ · ยาแก้ปวด · ยาฆ่าเชื้อ)
create type public.tx_code as enum (
  'tourniquet',            -- สายรัด / ขันชะเนาะ
  'hemostatic',            -- ผงห้ามเลือด
  'wound_dressing',        -- ผ้าแต่งแผล
  'splint',                -- ดามกระดูก
  'airway',                -- ใส่ท่อปาก/ท่อจมูก/เจาะคอ
  'chest_seal',            -- ปิดด้วยผ้า (แผลทะลุทรวงอก)
  'needle_decompression',  -- เข็มระบาย
  'chest_tube',            -- ท่อระบาย
  'oxygen',                -- ออกซิเจน
  'iv_fluid',              -- น้ำเกลือ NS / LR
  'analgesic',             -- ยาแก้ปวด
  'antibiotic',            -- ยาฆ่าเชื้อ
  'txa',                   -- tranexamic acid
  'other'
);
