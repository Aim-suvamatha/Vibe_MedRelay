/**
 * มัธยฐานของชุดตัวเลข — คืน null เมื่อไม่มีข้อมูล
 *
 * ★ ใช้ median ไม่ใช่ mean ตามข้อกำหนด Prompt 09 และมีเหตุผลจริง
 *   เวลาตอบสนองมี outlier เสมอ ทอดเดียวที่ติดฝนหรือรอเคลียร์เส้นทางสามชั่วโมง
 *   จะดึงค่าเฉลี่ยของทั้งเดือนให้เพี้ยนจนไม่สะท้อนวันปกติเลย
 *   ผู้บังคับบัญชาที่อ่านตัวเลขนี้ต้องการรู้ว่า "ปกติแล้วนานเท่าไร"
 *
 * ★ คืน null ไม่ใช่ 0 เมื่อไม่มีข้อมูล
 *   0 แปลว่า "วัดแล้วได้ศูนย์" ซึ่งคนละความหมายกับ "ยังไม่มีอะไรให้วัด"
 *
 * จำนวนคู่ใช้ค่าเฉลี่ยของสองตัวกลางตามนิยามมาตรฐาน
 */
export function median(values: readonly number[]): number | null {
  const xs = values
    .filter((v) => Number.isFinite(v))
    .slice()
    .sort((a, b) => a - b);
  if (xs.length === 0) return null;

  const mid = Math.floor(xs.length / 2);
  return xs.length % 2 === 1 ? xs[mid] : (xs[mid - 1] + xs[mid]) / 2;
}

/**
 * วินาที -> ข้อความไทยที่อ่านแล้วเข้าใจทันที
 * คืนขีดกลางเมื่อไม่มีข้อมูล ห้ามคืน "0 นาที" ซึ่งอ่านได้ว่าวัดแล้วได้ศูนย์
 */
export function formatDuration(sec: number | null): string {
  if (sec === null) return "—";

  const total = Math.max(0, Math.round(sec));
  if (total < 60) return `${total} วินาที`;

  /**
   * ต่ำกว่าหนึ่งชั่วโมงบอกวินาทีที่เหลือด้วย
   *
   * ⚠ อย่าปัดเป็นนาทีเฉยๆ ในช่วงนี้ — มัธยฐานรอจัดรถของข้อมูลจริงคือ 510 วินาที
   *   ถ้าปัดจะได้ "9 นาที" ทั้งที่ค่าจริงคือ 8 นาที 30 วินาที
   *   ตัวเลขนี้เป็นข้อพิสูจน์หลักที่โครงการเอาไปอ้าง การปัดขึ้นครึ่งนาที
   *   ทำให้เลขบนจอไม่ตรงกับเลขในเอกสาร ซึ่งเป็นเรื่องที่อธิบายยากตอนถูกถาม
   */
  if (total < 3600) {
    const mins = Math.floor(total / 60);
    const secs = total % 60;
    return secs ? `${mins} นาที ${secs} วินาที` : `${mins} นาที`;
  }

  // เกินหนึ่งชั่วโมงแล้ว วินาทีไม่ช่วยให้ตัดสินใจอะไรเพิ่ม ปัดเป็นนาทีได้
  const mins = Math.round(total / 60);
  const hours = Math.floor(mins / 60);
  const rest = mins % 60;
  if (hours < 24) return rest ? `${hours} ชม. ${rest} นาที` : `${hours} ชม.`;

  const days = Math.floor(hours / 24);
  return `${days} วัน ${hours % 24} ชม.`;
}
